parse_table() {
  # local fields="${1:-1-}"
  # local skip=${2:-1}

  sed '/^[[:space:]]*$/d' \
  | awk -F'|' -v skip="$skip" '
  {
    if (NR == 1) {
      print
      next
    }

    separator = 1

    for (i = 2; i <= NF - 1; i++) {
      field = $i
      gsub(/[[:space:]]/, "", field)

      if (field !~ /^:?-+:?$/) {
        separator = 0
        break
      }
    }

    if (separator)
      next

    for (i = 2; i <= NF - 1; i++) {
      gsub(/\*\*/, "", $i)
      gsub(/[$%,d]/, "", $i)
      gsub(/[[:space:]]+/, "", $i)
    }

    if ($2 == "")
      next

    output = sprintf("%-6s |", $2);
    for (i = 3; i <= NF - 1; i++)
      output = output sprintf("%10s |", $i);

    print output
  }' \
  ;
  # | cut --delimiter="|" --fields=${fields} \
  # | tail --lines=+$((skip + 1)) \

  return 0;
}

